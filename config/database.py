import mysql.connector
from mysql.connector import pooling
import os
import re
from dotenv import load_dotenv

load_dotenv()  # Carga variables de entorno desde .env

class Database:
    """Clase para manejar las conexiones a la base de datos MySQL."""
    _instance = None
    _pool = None

    @property
    def is_postgres(self):
        return bool(os.getenv('DATABASE_URL'))
    
    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(Database, cls).__new__(cls)
            if os.getenv('DATABASE_URL'):
                return cls._instance
            try:
                # Creación del pool de conexiones para mejor rendimiento
                cls._pool = mysql.connector.pooling.MySQLConnectionPool(
                    pool_name="ti_pool",
                    pool_size=5,  # Número de conexiones en el pool
                    host=os.getenv("DB_HOST", "localhost"),
                    port=int(os.getenv("DB_PORT", "3306")),
                    user=os.getenv("DB_USER", "root"),
                    password=os.getenv("DB_PASSWORD", ""),
                    database=os.getenv("DB_NAME", "ti_management")
                )
                print("Pool de conexiones creado correctamente")
            except mysql.connector.Error as err:
                print(f"Error al crear pool de conexiones: {err}")
                raise
        return cls._instance
    
    def get_connection(self):
        """Obtiene una conexión del pool."""
        if self.is_postgres:
            import psycopg
            return PostgresConnection(psycopg.connect(
                os.environ['DATABASE_URL'], prepare_threshold=None,
                connect_timeout=15))
        try:
            return self._pool.get_connection()
        except mysql.connector.Error as err:
            print(f"Error al obtener conexión: {err}")
            raise
    
    def execute_query(self, query, params=None):
        """Ejecuta una consulta de selección y devuelve resultados."""
        conn = None
        cursor = None
        try:
            conn = self.get_connection()
            cursor = conn.cursor(dictionary=True)
            cursor.execute(query, params or ())
            result = cursor.fetchall()
            return result
        except mysql.connector.Error as err:
            print(f"Error en execute_query: {err}")
            print(f"Query: {query}")
            raise
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()
    
    def execute_update(self, query, params=None, return_id=False):
        """Ejecuta una consulta de inserción/actualización/eliminación."""
        conn = None
        cursor = None
        try:
            conn = self.get_connection()
            cursor = conn.cursor()
            cursor.execute(query, params or ())
            affected_rows = cursor.lastrowid if return_id else cursor.rowcount
            conn.commit()
            return affected_rows
        except mysql.connector.Error as err:
            if conn:
                conn.rollback()
            print(f"Error en execute_update: {err}")
            print(f"Query: {query}")
            raise
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()


def postgres_sql(query):
    """Compatibilidad acotada para las consultas heredadas de MySQL."""
    query = re.sub(r'UTC_TIMESTAMP\(6\)', "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')", query, flags=re.I)
    query = re.sub(r'INTERVAL (%s|\d+) (HOUR|SECOND)\b',
                   lambda m: "(" + m[1] + " * INTERVAL '1 " + m[2].lower() + "')", query, flags=re.I)
    query = re.sub(r'TIMESTAMPDIFF\(MICROSECOND,\s*started_at,\s*%s\)/1000',
                   'EXTRACT(EPOCH FROM (%s::timestamp - started_at))*1000', query, flags=re.I)
    query = query.replace('INT AUTO_INCREMENT PRIMARY KEY', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    query = re.sub(r'\bDATETIME(?:\(6\))?', 'TIMESTAMP', query, flags=re.I)
    return query


class PostgresConnection:
    """Mantiene el contrato de los modelos durante la transición a PostgreSQL."""
    def __init__(self, connection):
        self.connection = connection

    def cursor(self, dictionary=False):
        from psycopg.rows import dict_row, tuple_row
        return PostgresCursor(self.connection.cursor(row_factory=dict_row if dictionary else tuple_row))

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


class PostgresCursor:
    def __init__(self, cursor):
        self.cursor = cursor
        self.lastrowid = None

    @property
    def rowcount(self):
        return self.cursor.rowcount

    def execute(self, query, params=None):
        query = postgres_sql(query).strip().rstrip(';')
        returns_id = bool(re.match(r'INSERT\s+INTO\s+(?:users|areas|assets|tickets|ticket_comments|monitoring_data|api_keys|notifications)\b', query, re.I)) and 'RETURNING' not in query.upper()
        if returns_id:
            query += ' RETURNING id'
        self.cursor.execute(query, params or None)
        if returns_id:
            row = self.cursor.fetchone()
            self.lastrowid = row['id'] if isinstance(row, dict) else row[0]

    def fetchall(self):
        return self.cursor.fetchall()

    def fetchone(self):
        return self.cursor.fetchone()

    def close(self):
        self.cursor.close()

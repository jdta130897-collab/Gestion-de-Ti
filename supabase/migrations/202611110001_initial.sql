CREATE TABLE IF NOT EXISTS areas (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(20) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL UNIQUE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('super_admin','admin','manager','technician','user')),
 created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE, area_id INTEGER REFERENCES areas(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower ON users (LOWER(email));
CREATE TABLE IF NOT EXISTS assets (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, type VARCHAR(50) NOT NULL, status VARCHAR(50) NOT NULL,
 purchase_date DATE NOT NULL, assigned_to INTEGER REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS tickets (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(100) NOT NULL, description TEXT NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('open','in_progress','resolved','closed')),
 priority VARCHAR(20) NOT NULL CHECK (priority IN ('low','medium','high','critical')),
 created_by INTEGER NOT NULL REFERENCES users(id),
 assigned_to INTEGER REFERENCES users(id) ON DELETE SET NULL,
 related_asset INTEGER REFERENCES assets(id) ON DELETE SET NULL,
 created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL, resolved_at TIMESTAMP,
 origin_area_id INTEGER REFERENCES areas(id), destination_area_id INTEGER REFERENCES areas(id),
 request_kind VARCHAR(20) NOT NULL DEFAULT 'incident' CHECK (request_kind IN ('incident','request')),
 channel VARCHAR(10) NOT NULL DEFAULT 'manual' CHECK (channel IN ('manual','voice'))
);
CREATE TABLE IF NOT EXISTS ticket_comments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id INTEGER NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id), comment TEXT NOT NULL, created_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS monitoring_data (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id INTEGER NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
 metric_name VARCHAR(50) NOT NULL, metric_value REAL NOT NULL, timestamp TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS api_keys (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 api_key VARCHAR(255) NOT NULL, expiry_date TIMESTAMP NOT NULL,
 created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS creation_attempts (
 id CHAR(36) PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 origin_area_id INTEGER NOT NULL REFERENCES areas(id),
 channel VARCHAR(10) NOT NULL CHECK (channel IN ('manual','voice')),
 request_kind VARCHAR(20) NOT NULL CHECK (request_kind IN ('incident','request')),
 started_at TIMESTAMP NOT NULL, submitted_at TIMESTAMP, finished_at TIMESTAMP,
 outcome VARCHAR(20) NOT NULL DEFAULT 'started' CHECK (outcome IN ('started','processing','success','failed','abandoned')),
 preparation_ms DOUBLE PRECISION, processing_ms DOUBLE PRECISION, total_ms DOUBLE PRECISION,
 ticket_id INTEGER REFERENCES tickets(id) ON DELETE SET NULL, word_count INTEGER
);
CREATE TABLE IF NOT EXISTS notifications (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 ticket_id INTEGER NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
 kind VARCHAR(30) NOT NULL, message VARCHAR(255) NOT NULL, created_at TIMESTAMP NOT NULL, read_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_attempt_scope ON creation_attempts(user_id,origin_area_id,started_at);
CREATE INDEX IF NOT EXISTS ix_attempt_ticket ON creation_attempts(ticket_id);
CREATE INDEX IF NOT EXISTS ix_notification_inbox ON notifications(user_id,read_at,created_at);
CREATE INDEX IF NOT EXISTS ix_ticket_creator ON tickets(created_by);
CREATE INDEX IF NOT EXISTS ix_ticket_origin ON tickets(origin_area_id);
CREATE INDEX IF NOT EXISTS ix_ticket_assignee ON tickets(assigned_to);
CREATE INDEX IF NOT EXISTS ix_comment_ticket ON ticket_comments(ticket_id);
CREATE INDEX IF NOT EXISTS ix_monitor_asset ON monitoring_data(asset_id,timestamp);
